static const char *fmt_milli(char *buf, size_t len, int32_t value, unsigned decimals)
{
  static const uint32_t div[] = { 1000U, 100U, 10U, 1U };
  uint32_t mag = (value < 0) ? (uint32_t)(-(int64_t)value) : (uint32_t)value;
  const char *sign = (value < 0) ? "-" : "";
  if (decimals == 0U) {
    snprintf(buf, len, "%s%lu", sign, (unsigned long)(mag / 1000U));
  } else {
    snprintf(buf, len, "%s%lu.%0*lu", sign, (unsigned long)(mag / 1000U), (int)decimals,
             (unsigned long)((mag % 1000U) / div[decimals]));
  }
  return buf;
}

static void ina219_bring_up(void)
{
  char line[128], shunt[16];
  while (ina219_init(&s_ina) != HAL_OK) {
    s_errors++;
    snprintf(line, sizeof(line), "INA219 @0x%02X: init FAIL (I2C err 0x%lX), retrying\r\n",
             (unsigned)(INA219_ADDR >> 1), (unsigned long)HAL_I2C_GetError(&hi2c1));
    uart_print(line);
    HAL_Delay(1000U);
  }
  uint16_t config = 0U, calib = 0U;
  (void)ina219_read_reg(&s_ina, INA219_REG_CONFIG, &config);
  (void)ina219_read_reg(&s_ina, INA219_REG_CALIB, &calib);
  snprintf(line, sizeof(line), "INA219 @0x%02X: init OK, config=0x%04X calib=0x%04X shunt=%s mohm LSB=%lu uA\r\n",
           (unsigned)(INA219_ADDR >> 1), config, calib,
           fmt_milli(shunt, sizeof(shunt), (int32_t)INA219_SHUNT_UOHM, 3), (unsigned long)INA219_CURRENT_LSB_UA);
  uart_print(line);
}
